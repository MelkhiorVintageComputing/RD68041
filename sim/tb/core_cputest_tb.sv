// RD68041 -- WinUAE's cputest corpus, run on the core.
//
// cputest is a vector set made to be run on real processors: a generator
// (WinUAE's cputestgen, built by tools/cputest/build.sh) writes, for every
// opcode it knows, the starting registers and memory and the registers,
// memory writes and exception it expects. tools/cputest/convert.py replays the
// runner's bookkeeping and writes what this bench needs as a flat stream (its
// BENCH_FORMAT). RD68031's core_cputest_tb is the model; what differs is how a
// test gets into the core and out of it.
//
// The corpus's runner enters every test with an RTE and leaves it through an
// exception: the ILLEGAL it puts after the instruction (the sentinel), or the
// one the test is about. Here each test is put in the way core_vec_tb puts
// one: the core reset into the test's PC (the reset vectors at 0 and 4 lent
// for the length of the reset), the registers deposited -- the SR the test
// starts from, A7 the user stack pointer, the ISP and MSP the runner's -- and
// the instruction run alone (rd68041_core_harness.svh), with the exception
// processing that follows it. A test of the FPU's (M11) has FP0-FP7, FPCR,
// FPSR and FPIAR deposited too, the FPU idle, as the runner's FMOVEMs leave it.
// Then compared: D0-D7, A0-A6, the USP, the FPU's registers in a test of the
// FPU's, every memory write the test was to make, and
//   - if the test ends at the sentinel: the SR under the corpus's mask of
//     undefined flags, and the next PC -- the sentinel's address, or the
//     address of the runner's NOP (MOVEA.L A0,A0, which changes nothing)
//     just before it;
//   - if it ends in an exception of its own: the frame it built on the
//     supervisor stack -- the stacked SR under the mask, the PC, the format
//     and vector word, and a format $2 or $3 frame's address.
// The vector table is wherever the test's memory puts it (VBR is zero): the
// handler is not run, and an odd one, a double bus fault on the vector
// fetch, leaves the frame built all the same.
//
// Each test is one of:
//   PASS        it ran, and everything compared agreed;
//   FAIL        it ran, and something did not (or it never finished);
//   NOT BUILT   the core halted on it: its decoder does not build it yet;
//   PENDING     what it needs is not built: a test of the FPU's in an
//               MC68LC040 build (FPU=0, until M12). Not run.
// The bench PASSes when nothing FAILs.
//
// The corpus is generated by UAE's own instruction core; like every oracle
// here it is an ORACLE, not a source, and where it and the core disagree the
// manual decides.
//
//   +vec=<dir>/cputest.vec   the stream          (default build/cputest/cputest.vec)
//   +mem=<dir>               lmem<N>.hex, tmem<N>.hex (default build/cputest)
//   +idx=<dir>/cputest.idx   test number -> instruction, for the summary
//   +faillog=<file>          one line per failing test: id, what, got, expected
//   +show=N                  how many failures to print (default 25)
//   +trace=<id>              that test alone traced: the harness's +xtrace, and
//                            the pipeline's stages every clock

`timescale 1ns / 1ps

module core_cputest_tb;

`include "rd68041_core_harness.svh"
`include "rd68041_vec_harness.svh"

  localparam int MAXMN = 512;

  integer      vec, flog, fidx;
  string       vecfile, memdir, flogfile, idxfile, why, lfile, tfile;
  int unsigned kind, n, k, cnt;
  int unsigned id, w0, w1;
  logic [31:0] a, b, c;
  logic [31:0] pc0, sr0, ssp0, msp0;
  logic [31:0] d0 [0:7];
  logic [31:0] a0 [0:7];
  logic [31:0] evec, epc, efmt, naddr, eaddr, skipregs, esr, esrmask;
  logic [31:0] ed [0:7];
  logic [31:0] ea [0:7];
  // The FPU's: the flag, FPCR, FPSR, FPIAR, then FP0-FP7 as exponent word,
  // high and low long words; f0 in, ef expected.
  logic [31:0] f0 [0:27];
  logic [31:0] ef [0:27];
  int unsigned nwr;
  logic [31:0] wr_a [0:63];
  logic [31:0] wr_s [0:63];
  logic [31:0] wr_n [0:63];
  logic [31:0] wr_o [0:63];
  logic [7:0]  lent [0:7];

  // Per instruction (mnemonic), from the .idx file: the id ranges.
  string       mname [0:MAXMN-1];
  int unsigned mfirst[0:MAXMN-1];
  int unsigned m_pass[0:MAXMN-1];
  int unsigned m_fail[0:MAXMN-1];
  int unsigned m_nb  [0:MAXMN-1];
  int unsigned m_pend[0:MAXMN-1];
  int unsigned nmn, cur_mn;
  reg [8*1024:1] lbuf;
  reg [8*24:1] mbuf;

  int unsigned ntests, passed, failed, notbuilt, pending, shown, maxshow;
  int          trace_id;
  // A double bus fault during exception processing, seen as it happens.
  bit          dbl_seen;
  always @(posedge clk) if (dut.u_core.w_dbl) dbl_seen = 1'b1;
  bit          ok, built, bad, user;
  logic [31:0] got, npc, srm;
  logic [79:0] fpv, fpe;

  // +trace=<id>: the pipeline, clock by clock, while that test runs.
  bit          pt_on;
  always @(negedge clk)
    if (pt_on && cap_on)
      $display("  [%0d] ea %b%b %h fpk%0d | of %b %h fpk%0d rdy%b | ex %b %h fpk%0d fw%b | w %b %h fpk%0d wst%b | st %b%b rec %b%b ph%0d",
               cyc, dut.u_core.ea_u.valid, dut.u_core.ea_u.last, dut.u_core.ea_u.pc, dut.u_core.ea_u.fpk,
               dut.u_core.of_u.valid, dut.u_core.of_u.pc, dut.u_core.of_u.fpk, dut.u_core.of_ready,
               dut.u_core.ex_u.valid, dut.u_core.ex_u.pc, dut.u_core.ex_u.fpk, dut.u_core.fp_wait,
               dut.u_core.w_u.valid, dut.u_core.w_u.pc, dut.u_core.w_u.fpk, dut.u_core.w_stall,
               dut.u_core.ea_stall, dut.u_core.ex_stall, dut.u_core.u_fpu.rec_v, dut.u_core.u_fpu.rec_w,
               dut.u_core.u_fpu.ph);

  function automatic logic [31:0] rd8(input logic [31:0] x);
    rd8 = {24'd0, rb(x)};
  endfunction
  function automatic logic [31:0] rd16(input logic [31:0] x);
    rd16 = {16'd0, rw(x)};
  endfunction

  task automatic read_fp(input bit expected);
    logic [31:0] v;
    for (k = 0; k < 28; k++) begin
      void'($fscanf(vec, "%h", v));
      if (expected) ef[k] = v;
      else          f0[k] = v;
    end
  endtask

  // The bytes before and after a test, and the stack copy.
  task automatic patches();
    void'($fscanf(vec, "%h", cnt));
    for (k = 0; k < cnt; k++) begin
      void'($fscanf(vec, "%h %h", a, b));
      mb(a, b[7:0]);
    end
  endtask

  task automatic copies();
    void'($fscanf(vec, "%h", cnt));
    for (k = 0; k < cnt; k++) begin
      void'($fscanf(vec, "%h %h %h", a, b, c));
      for (n = 0; n < c; n++) mb(b + n, rb(a + n));
    end
  endtask

  task automatic note(input string what, input logic [31:0] g, input logic [31:0] e);
    if (why == "") $sformat(why, "%s is %08h, the corpus says %08h", what, g, e);
    if (flog != 0) $fdisplay(flog, "%0h %s %s %08h %08h", id, mname[cur_mn], what, g, e);
  endtask

  // The instruction a test id belongs to (the ids run in .idx order).
  task automatic find_mn(input int unsigned tid);
    while (cur_mn + 1 < nmn && mfirst[cur_mn + 1] <= tid) cur_mn++;
  endtask

  // One test, read: classify it, and run and compare it if it is to run.
  task automatic one_test();
    bit          sentinel;
    logic [31:0] sp;
    begin : body
      find_mn(id);
      if (trace_id >= 0) begin
        xtrace_on = (id == trace_id);
        pt_on     = (id == trace_id);
      end
      if (f0[0] != 0 && `TB_FPU == 0) begin
        pending++;
        m_pend[cur_mn]++;
        disable body;
      end
      user = !sr0[13];
      // The sentinel is the ILLEGAL after the instruction; an illegal
      // instruction exception at the instruction itself is the test's own.
      sentinel = (evec == 4) && (epc != pc0);

      // ------------------------------------------------------------------
      // In: a reset into the test's PC, and the registers deposited.
      // ------------------------------------------------------------------
      for (n = 0; n < 8; n++) lent[n] = rb(n);
      ml(0, ssp0);
      ml(4, pc0);
      vec_boot();
      for (n = 0; n < 8; n++) dep_d[n] = d0[n];
      for (n = 0; n < 7; n++) dep_a[n] = a0[n];
      dep_usp = a0[7];
      dep_isp = ssp0;
      dep_msp = msp0;
      dep_sr  = sr0[15:0];
      deposit();
      if (f0[0] != 0) begin
        dut.u_core.u_fpu.fpcr  = f0[1][15:0];
        dut.u_core.u_fpu.fpsr  = f0[2];
        dut.u_core.u_fpu.fpiar = f0[3];
        for (n = 0; n < 8; n++)
          dut.u_core.u_fpu.fpr[n] = {f0[4 + 3*n][15:0], f0[5 + 3*n], f0[6 + 3*n]};
        dut.u_core.u_fpu.st   = rd68041_fpu_pkg::ST_IDLE;
        dut.u_core.u_fpu.pend = 1'b0;
      end
      for (n = 0; n < 8; n++) mb(n, lent[n]);
      cap_clear();
      cap_on = 1'b1;
      dbl_seen = 1'b0;
      // An exception of the test's own past its instruction (a trace it turned
      // on, taken after the runner's next instruction): run on until it.
      run_free = !sentinel && (epc != pc0);
      // The FNOP the generator puts after an FPU instruction is the test's.
      run_more = f0[0][1] ? 1 : 0;
      run_one(4000, ok, built);
      run_free = 1'b0;
      run_more = 0;
      cap_on = 1'b0;
      // A double bus fault on the vector fetch (an odd handler): the frame is
      // built, and that is what is compared.
      if (!built && dbl_seen) begin built = 1'b1; ok = 1'b1; end
      end_one();
      // Copyback: what the test wrote may still be in the data cache.
      if (dep_cache == 2) dc_writeback();

      if (!built) begin
        undo_writes();
        notbuilt++;
        m_nb[cur_mn]++;
        disable body;
      end

      // ------------------------------------------------------------------
      // Compare.
      // ------------------------------------------------------------------
      why = "";
      bad = 1'b0;
      if (!ok) note("completion (it never finished)", 32'd0, 32'd1);
      srm = esrmask & 32'h0000_FFFF;
      if (sentinel) begin
        npc = last_npc;
        // The runner's NOP before the sentinel changes nothing; the core has
        // not run it.
        if (nretire != 0 && npc !== epc && !(rw(npc) == 16'h2048 && npc + 2 == epc))
          note("the next PC", npc, epc);
        if (nretire == 0) note("the retirement count", 32'd0, 32'd1);
        if (((dut.u_core.sr ^ esr[15:0]) & srm[15:0]) != 16'd0)
          note("SR", {16'd0, dut.u_core.sr}, esr);
      end else begin
        // The frame, on the supervisor stack M names (UM 8.4).
        sp = sp_of(dut.u_core.sr_sys[4] ? 2 : 1);
        if (((rw(sp) ^ esr[15:0]) & srm[15:0]) != 16'd0) note("the stacked SR", {16'd0, rw(sp)}, esr);
        if (rl(sp + 2) !== epc) note("the stacked PC", rl(sp + 2), epc);
        if ({16'd0, rw(sp + 6)} !== efmt) note("the format and vector word", {16'd0, rw(sp + 6)}, efmt);
        if (naddr != 0 && rl(sp + 8) !== eaddr) note("the frame's address", rl(sp + 8), eaddr);
      end
      if (!skipregs[0]) begin
        for (n = 0; n < 8; n++)
          if (reg_of(n) !== ed[n]) note($sformatf("D%0d", n), reg_of(n), ed[n]);
        for (n = 0; n < 7; n++)
          if (reg_of(8 + n) !== ea[n]) note($sformatf("A%0d", n), reg_of(8 + n), ea[n]);
        if (sp_of(0) !== ea[7]) note("the USP", sp_of(0), ea[7]);
        if (ef[0] != 0) begin
          if ({16'd0, dut.u_core.u_fpu.fpcr} !== ef[1]) note("FPCR", {16'd0, dut.u_core.u_fpu.fpcr}, ef[1]);
          if (dut.u_core.u_fpu.fpsr !== ef[2]) note("FPSR", dut.u_core.u_fpu.fpsr, ef[2]);
          if (dut.u_core.u_fpu.fpiar !== ef[3]) note("FPIAR", dut.u_core.u_fpu.fpiar, ef[3]);
          for (n = 0; n < 8; n++) begin
            fpv = dut.u_core.u_fpu.fpr[n];
            fpe = {ef[4 + 3*n][15:0], ef[5 + 3*n], ef[6 + 3*n]};
            // A NaN's or an infinity's integer bit is a don't care (UM Table 9-5).
            if (fpv[78:64] == 15'h7FFF && fpe[78:64] == 15'h7FFF) begin
              fpv[63] = 1'b0;
              fpe[63] = 1'b0;
            end
            if (fpv[79:64] !== fpe[79:64])
              note($sformatf("FP%0d's exponent", n), {16'd0, fpv[79:64]}, {16'd0, fpe[79:64]});
            else if (fpv[63:32] !== fpe[63:32])
              note($sformatf("FP%0d's mantissa, high", n), fpv[63:32], fpe[63:32]);
            else if (fpv[31:0] !== fpe[31:0])
              note($sformatf("FP%0d's mantissa, low", n), fpv[31:0], fpe[31:0]);
          end
        end
      end
      for (n = 0; n < nwr; n++) begin
        got = (wr_s[n] == 1) ? rd8(wr_a[n]) : (wr_s[n] == 2) ? rd16(wr_a[n]) : rl(wr_a[n]);
        if (got !== wr_n[n]) note($sformatf("the %0d-byte write at %08h", wr_s[n], wr_a[n]), got, wr_n[n]);
      end
      undo_writes();

      if (why == "") begin
        passed++;
        m_pass[cur_mn]++;
      end else begin
        failed++;
        m_fail[cur_mn]++;
        if (shown < maxshow) begin
          shown++;
          $display("  FAIL: test %0h %s (%04h %04h): %s", id, mname[cur_mn], w0[15:0],
                   w1[15:0], why);
          $display("        from SR=%04h D=%08h %08h %08h %08h %08h %08h %08h %08h", sr0[15:0],
                   d0[0], d0[1], d0[2], d0[3], d0[4], d0[5], d0[6], d0[7]);
          $display("             A=%08h %08h %08h %08h %08h %08h %08h %08h", a0[0], a0[1],
                   a0[2], a0[3], a0[4], a0[5], a0[6], a0[7]);
        end
      end
    end
  endtask

  initial begin
    if (!$value$plusargs("vec=%s", vecfile)) vecfile = "build/cputest/cputest.vec";
    if (!$value$plusargs("mem=%s", memdir)) memdir = "build/cputest";
    if (!$value$plusargs("idx=%s", idxfile)) idxfile = {memdir, "/cputest.idx"};
    if (!$value$plusargs("show=%d", maxshow)) maxshow = 25;
    if (!$value$plusargs("trace=%h", trace_id)) trace_id = -1;
    pt_on = 1'b0;
    flog = 0;
    if ($value$plusargs("faillog=%s", flogfile)) flog = $fopen(flogfile, "w");
    if ($bits(rd68041_pkg::uop_t) != rd68041_pkg::UOP_W) begin
      $display("FAIL: rd68041_pkg::UOP_W is %0d, the struct %0d bits",
               rd68041_pkg::UOP_W, $bits(rd68041_pkg::uop_t));
      $finish;
    end
    vec = $fopen(vecfile, "r");
    if (vec == 0) begin
      $display("FAIL: core_cputest_tb cannot open %s", vecfile);
      $finish;
    end

    // The instructions, from the index: "<id> <mnemonic> ...", one per test.
    nmn = 0;
    fidx = $fopen(idxfile, "r");
    if (fidx != 0) begin
      while (!$feof(fidx) && nmn < MAXMN) begin
        if ($fscanf(fidx, "%h %s", id, mbuf) == 2) begin
          if (nmn == 0 || mname[nmn - 1] != $sformatf("%0s", mbuf)) begin
            mname[nmn] = $sformatf("%0s", mbuf);
            mfirst[nmn] = id;
            nmn++;
          end
        end
        void'($fgets(lbuf, fidx));
      end
      $fclose(fidx);
    end
    if (nmn == 0) begin mname[0] = "?"; mfirst[0] = 0; nmn = 1; end
    for (n = 0; n < nmn; n++) begin
      m_pass[n] = 0; m_fail[n] = 0; m_nb[n] = 0; m_pend[n] = 0;
    end
    cur_mn = 0;

    ntests = 0; passed = 0; failed = 0; notbuilt = 0; pending = 0; shown = 0;
    kind = 0;
    while (kind != 3) begin
      if ($fscanf(vec, "%h", kind) != 1) begin
        $display("FAIL: core_cputest_tb: the stream ends without its end record");
        kind = 3;
        failed++;
      end
      if (kind == 3) ;
      else if (kind == 2) begin
        void'($fscanf(vec, "%h", k));
        $sformat(lfile, "%s/lmem%0d.hex", memdir, k);
        $sformat(tfile, "%s/tmem%0d.hex", memdir, k);
        for (n = 0; n < VMEM; n++) u_mem.mem[n] = 8'h00;
        $readmemh(lfile, u_mem.mem);
        $readmemh(tfile, u_mem.mem);
        patches();
        copies();
        patches();
      end else begin
        patches();
        copies();
        if (kind == 0) begin
          void'($fscanf(vec, "%h %h %h", id, w0, w1));
          void'($fscanf(vec, "%h %h", pc0, sr0));
          for (n = 0; n < 8; n++) void'($fscanf(vec, "%h", d0[n]));
          for (n = 0; n < 8; n++) void'($fscanf(vec, "%h", a0[n]));
          void'($fscanf(vec, "%h %h", ssp0, msp0));
          read_fp(1'b0);
          void'($fscanf(vec, "%h %h %h %h %h", evec, epc, efmt, naddr, eaddr));
          void'($fscanf(vec, "%h", skipregs));
          for (n = 0; n < 8; n++) void'($fscanf(vec, "%h", ed[n]));
          for (n = 0; n < 8; n++) void'($fscanf(vec, "%h", ea[n]));
          void'($fscanf(vec, "%h %h", esr, esrmask));
          read_fp(1'b1);
          void'($fscanf(vec, "%h", nwr));
          for (n = 0; n < nwr; n++)
            void'($fscanf(vec, "%h %h %h %h", wr_a[n], wr_s[n], wr_n[n], wr_o[n]));
          ntests++;
          one_test();
          if ((ntests % 5000) == 0)
            $display("  .. %0d tests, %0d failed", ntests, failed);
        end
        patches();
      end
    end

    $fclose(vec);
    if (flog != 0) $fclose(flog);
    $display("core_cputest_tb: %-12s %7s %7s %9s %10s", "instruction", "passed", "failed",
             "not built", "pending");
    // Only the instructions with something not passed; the rest are counted.
    k = 0;
    for (n = 0; n < nmn; n++)
      if (m_fail[n] + m_nb[n] + m_pend[n] != 0)
        $display("core_cputest_tb: %-12s %7d %7d %9d %10d", mname[n], m_pass[n], m_fail[n],
                 m_nb[n], m_pend[n]);
      else if (m_pass[n] != 0)
        k++;
    $display("core_cputest_tb: ... and %0d instructions whose every test passed", k);
    $display("core_cputest_tb: %0d passed, %0d failed, %0d not built, %0d pending, of %0d",
             passed, failed, notbuilt, pending, ntests);
    if (failed == 0 && ntests != 0) $display("PASS: core_cputest_tb");
    else                             $display("FAIL: core_cputest_tb");
    $finish;
  end

endmodule
